"""Write an attractor-switch impulse sweep for every model in a bundle folder.

Uses the settings of conf/experiments/emoji_attractor_switch_example.yaml,
but makes one run per model and per ordered pair of its patterns
(source -> target), instead of a single model with 0 -> 1 and 1 -> 0.

    python -m Experiments.impulse.make_switch_sweep
    python -m Experiments.impulse.make_switch_sweep --only-complete --manifest

- Pattern count K is read from each bundle's config.yaml (data.emoji.pairs),
  so models with 2, 3, 4 or 5 patterns get K(K-1) transitions each.
- --only-complete skips bundles whose training diverged (status: failed).
- --manifest also writes conf/generated/<name>/manifest.yaml.
- --store-root sets checkpoint.store_root (default: models, the repo's local
  store). launch/launch_local_sweep.py points MODEL_STORE_ROOT at
  models/local/<name>, where these bundles are not, so the root is set here.
  Pass --store-root "" on a cluster to use its MODEL_STORE_ROOT instead.
"""

import argparse
from pathlib import Path

import yaml

from Experiments.config_workflow import REPO_ROOT, load_yaml


BASE_DIR = Path(__file__).resolve().parent
EXPERIMENTS_DIR = BASE_DIR / "conf" / "experiments"
EXAMPLE_SWEEP = EXPERIMENTS_DIR / "emoji_attractor_switch_example.yaml"
DEFAULT_BUNDLES = REPO_ROOT / "models" / "bundles" / "nca-emoji" / "emoji-multi-attractor-outsource"
DEFAULT_NAME = "emoji_attractor_switch_outsource"


def read_bundles(bundle_dir, only_complete=False):
    """Return (model_id, pattern_count, status) for every bundle in the folder."""

    bundles = []
    for manifest_path in sorted(Path(bundle_dir).glob("*/manifest.yaml")):
        manifest = load_yaml(manifest_path)
        config = load_yaml(manifest_path.parent / "config.yaml")
        emoji = config["data"]["emoji"]
        if emoji["task"] != "multi_attractor" or len(emoji["pairs"]) < 2:
            continue
        if only_complete and manifest["status"] != "complete":
            continue
        bundles.append((manifest["id"], len(emoji["pairs"]), manifest["status"]))
    return bundles


def transitions(bundles):
    """All ordered (model, source, target) triples, source != target."""

    model_ids, sources, targets = [], [], []
    for model_id, count, _ in bundles:
        for source in range(count):
            for target in range(count):
                if source != target:
                    model_ids.append(model_id)
                    sources.append(source)
                    targets.append(target)
    return model_ids, sources, targets


def build_sweep(bundles, name, store_root="models"):
    """Copy the example sweep and replace the model and the transitions."""

    sweep = load_yaml(EXAMPLE_SWEEP)
    sweep["experiment_name"] = name
    sweep["output_subdir"] = f"generated/{name}"
    # The model now changes with the transition, so it moves into the group block.
    sweep["grid"].pop("checkpoint.model_id")
    if store_root:
        sweep["grid"]["checkpoint.store_root"] = [store_root]
    model_ids, sources, targets = transitions(bundles)
    sweep["groups"] = [
        {
            "checkpoint.model_id": model_ids,
            "impulse.pair_source.source_index": sources,
            "impulse.pair_source.target_index": targets,
        }
    ]
    return sweep


def run_count(sweep):
    grid_runs = 1
    for values in sweep["grid"].values():
        grid_runs *= len(values)
    return grid_runs * len(sweep["groups"][0]["checkpoint.model_id"])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bundles", type=Path, default=DEFAULT_BUNDLES, help="folder with one sub-folder per model bundle")
    parser.add_argument("--name", default=DEFAULT_NAME, help="experiment name and sweep file name")
    parser.add_argument("--only-complete", action="store_true", help="skip bundles with status: failed")
    parser.add_argument("--manifest", action="store_true", help="also write the manifest")
    parser.add_argument("--store-root", default="models", help='model store holding the bundles ("" = use MODEL_STORE_ROOT)')
    args = parser.parse_args()

    bundles = read_bundles(args.bundles, only_complete=args.only_complete)
    if not bundles:
        raise SystemExit(f"No multi_attractor bundles found in {args.bundles}")
    sweep = build_sweep(bundles, args.name, store_root=args.store_root)

    failed = sum(status != "complete" for _, _, status in bundles)
    header = (
        f"# Generated by Experiments/impulse/make_switch_sweep.py from\n"
        f"# {EXAMPLE_SWEEP.name}. Do not edit by hand; rerun the script.\n"
        f"# Bundles: {args.bundles.name} ({len(bundles)} models, {failed} with status: failed)\n"
        f"# Transitions: {len(sweep['groups'][0]['checkpoint.model_id'])}, runs: {run_count(sweep)}\n"
    )
    sweep_path = EXPERIMENTS_DIR / f"{args.name}.yaml"
    with sweep_path.open("w") as handle:
        handle.write(header)
        yaml.safe_dump(sweep, handle, sort_keys=False, default_flow_style=None, width=120)
    print(header, end="")
    print(f"Wrote {sweep_path.relative_to(REPO_ROOT)}")

    if args.manifest:
        from Experiments.impulse.generate_configs import generate

        manifest = generate(args.name)
        print(f"Wrote manifest with {manifest['count']} configs to {manifest['output_dir']}")


if __name__ == "__main__":
    main()
